@Mixin(BlockLootSubProvider.class)
public abstract class BlockLootSubProviderMixin {
    @Shadow
    protected abstract LootTable.Builder createLeavesDrops(Block leavesBlock, Block saplingBlock, float... chances);

    @Inject(method = "createOakLeavesDrops",at = @At("RETURN"),cancellable = true)
    protected void newOakLeavesDrop(Block oakLeavesBlock, Block saplingBlock, float[] chances, CallbackInfoReturnable<LootTable.Builder> cir) {
        cir.setReturnValue(this.createLeavesDrops(oakLeavesBlock, saplingBlock, chances));
    }
}
